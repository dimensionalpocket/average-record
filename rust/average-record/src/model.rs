    #[tokio::test(flavor = "multi_thread")]
    async fn change_tracking_records_insert_update_and_delete() {
        let _guard = TEST_LOCK.lock().await;
        let mut conn = memory_connection().await;

        let mut model = TestModel {
            name: "foo".to_string(),
            status: "active".to_string(),
            ..Default::default()
        };
        model
            .save_with_options(
                &mut conn,
                SaveOptions {
                    track_changes: true,
                    ..Default::default()
                },
            )
            .await
            .unwrap();

        let changes = model.tracked_changes().unwrap();
        assert!(changes.get("name").unwrap().before.is_none());
        assert_eq!(
            changes
                .get("name")
                .unwrap()
                .after
                .as_ref()
                .and_then(SqlValue::as_str),
            Some("foo")
        );

        model.name = "bar".to_string();
        model
            .save_with_options(
                &mut conn,
                SaveOptions {
                    track_changes: true,
                    skip_updated_at: true,
                },
            )
            .await
            .unwrap();
        let changes = model.tracked_changes().unwrap();
        assert_eq!(changes.len(), 1);
        assert_eq!(
            changes
                .get("name")
                .unwrap()
                .before
                .as_ref()
                .and_then(SqlValue::as_str),
            Some("foo")
        );
        assert_eq!(
            changes
                .get("name")
                .unwrap()
                .after
                .as_ref()
                .and_then(SqlValue::as_str),
            Some("bar")
        );

        model
            .destroy_with_options(
                &mut conn,
                SaveOptions {
                    track_changes: true,
                    ..Default::default()
                },
            )
            .await
            .unwrap();
        let changes = model.tracked_changes().unwrap();
        assert!(changes.get("name").unwrap().after.is_none());
    }

